function matches(row, rules) {
  const codec = String(rules.codecProfile || "hevc").toLowerCase();
  const reelOk = !codec || String(row.reel || "").toLowerCase().includes(codec);
  const mode = String(rules.renderMode || "deferred").toLowerCase();
  const stateMap = { deferred: "queued", realtime: "active", batch: "staged" };
  const expectedState = stateMap[mode] || "queued";
  const stateOk = !mode || row.state === expectedState || (!rules.syncStrict && row.state === "ready");
  const budgetOk = Number(row.bitrate || 0) >= Number(rules.frameBudget || 0) / 4;
  const operatorKey = String(rules.operatorTag || "").trim().toLowerCase();
  const operatorOk = !operatorKey || String(row.operator || "").toLowerCase().includes(operatorKey);
  const strictOk = !rules.syncStrict || row.state === "ready";
  return reelOk && stateOk && budgetOk && operatorOk && strictOk;
}
function cell(value) {
  const td = document.createElement("td");
  td.textContent = String(value);
  return td;
}
function render(rows) {
  const body = document.querySelector("#clipRows");
  if (!body) return;
  while (body.firstChild) body.removeChild(body.firstChild);
  for (const row of rows) {
    const tr = document.createElement("tr");
    tr.appendChild(cell(row.clipId));
    tr.appendChild(cell(row.reel));
    tr.appendChild(cell(row.state));
    tr.appendChild(cell(row.operator));
    tr.appendChild(cell(row.bitrate + "k"));
    tr.appendChild(cell(row.age + "d"));
    tr.appendChild(cell(row.region));
    body.appendChild(tr);
  }
}
function paintSummary(rows) {
  const matchNode = document.querySelector("#segmentMatchCount");
  if (matchNode) matchNode.textContent = String(rows.length);
  document.documentElement.dataset.case010VisibleClips = String(rows.length);
}
export function rf(rules = {}) {
  const source = Array.isArray(rules.rows) ? rules.rows : [];
  const visible = source.filter((row) => matches(row, rules));
  render(visible);
  paintSummary(visible);
  return visible;
}

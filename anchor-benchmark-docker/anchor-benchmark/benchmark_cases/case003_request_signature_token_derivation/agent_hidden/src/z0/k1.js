export function weaveRoute(ctx, branches) {
  const routeValue = branches.reduce((value, branch, index) => Math.imul(value ^ branch.routeValue ^ index, 0x45d9f3b) >>> 0, ctx.row.weight);
  const routeSteps = branches.flatMap((branch) => [`branch:${branch.branch}`, ...branch.steps]);
  const branchKeys = branches.map((branch) => branch.branchKey).filter(Boolean);
  const branchWeight = branchKeys.reduce((sum, key, index) => sum + key.length * (index + 3), 0);
  const wovenValue = (routeValue ^ branchWeight ^ ctx.journalTicket) >>> 0;
  const graphTrace = branchKeys.map((key) => `key:${key}`);
  const graphWeight = graphTrace.join('|').length;
  const graphValue = (wovenValue ^ graphWeight) >>> 0;
  return { ...ctx, branches, branchKeys, branchWeight, graphWeight, routeValue: graphValue, routeSteps: routeSteps.concat(graphTrace) };
}

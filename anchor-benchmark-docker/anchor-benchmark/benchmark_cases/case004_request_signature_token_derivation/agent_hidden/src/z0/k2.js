export function finalizeRoute(ctx) {
  const branchNames = new Set(ctx.branches.map((branch) => branch.branch));
  const ready = branchNames.has('gesture') && branchNames.has('journal') && branchNames.has('policy') && ctx.row.policy === 'seal';
  const routeLengthWeight = ctx.meta.runtime.resourceLength * 13;
  const sliderWeight = ctx.meta.runtime.sliderBand << 9;
  const environmentWeight = ctx.meta.runtime.environmentIndex << 5;
  const routeValue = (ctx.routeValue ^ routeLengthWeight ^ sliderWeight ^ environmentWeight ^ (ctx.meta.runtime.grantIndex << 7)) >>> 0;
  const finalStep = `graph:final:${ready ? 1 : 0}`;
  const finalWeight = finalStep.length * 29;
  return { ...ctx, ready, routeValue: routeValue ^ finalWeight, routeLengthWeight, sliderWeight, environmentWeight, finalWeight, routeSteps: ctx.routeSteps.concat(finalStep) };
}

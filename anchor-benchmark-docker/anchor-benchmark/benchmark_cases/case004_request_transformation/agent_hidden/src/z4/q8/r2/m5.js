const alphabet = "0123456789abcdefghjkmnpqrstvwxyz";

function rotateLeft(value, amount) {
  return ((value << amount) | (value >>> (32 - amount))) >>> 0;
}

function normalizeTuple(tuple) {
  return tuple.slice().sort((a, b) => a.ix - b.ix).map((item, position) => ({
    ix: Number.isFinite(item.ix) ? item.ix : position,
    k: String(item.k || ""),
    v: String(item.v || ""),
    p: String(item.plain || "")
  }));
}

function makeTape(tuple) {
  const rows = normalizeTuple(tuple);
  const parts = [];
  for (const row of rows) {
    parts.push(String(row.ix));
    parts.push(":");
    parts.push(String(row.k.length));
    parts.push(":");
    parts.push(row.k);
    parts.push("=");
    parts.push(String(row.v.length));
    parts.push(":");
    parts.push(row.v);
    parts.push("~");
    parts.push(String(row.p.length));
    parts.push(":");
    parts.push(row.p);
    parts.push("|");
  }
  return parts.join("");
}

function makeBody(left, right, width) {
  let a = left >>> 0;
  let b = right >>> 0;
  let out = "";
  for (let i = 0; i < width; i += 1) {
    a = Math.imul(a ^ (b >>> ((i % 5) + 1)) ^ i, 0x27d4eb2d) >>> 0;
    b = Math.imul(b + rotateLeft(a, (i % 11) + 3) + i, 0x165667b1) >>> 0;
    out += alphabet[(a ^ b ^ (a >>> 7)) & 31];
  }
  return out;
}

function makeRecipe(slot) {
  return {
    slot,
    seed: (0x9e3779b9 ^ Math.imul(slot + 1, 0x45d9f3b)) >>> 0,
    mulA: (0x85ebca6b ^ slot) >>> 0,
    mulB: (0xc2b2ae35 ^ (slot << 3)) >>> 0,
    bias: (slot * 97 + 41) >>> 0
  };
}

const activeRecipe = makeRecipe(activeSlot);

function buildExportQueryPayload(tuple, context = {}) {
  const tape = makeTape(Array.isArray(tuple) ? tuple : []);
  let left = (activeRecipe.seed ^ tape.length ^ activeSlot) >>> 0;
  let right = (activeRecipe.bias + 0x27d4eb2d) >>> 0;
  for (let i = 0; i < tape.length; i += 1) {
    const code = tape.charCodeAt(i);
    left = Math.imul(left ^ code ^ (i + activeRecipe.bias), activeRecipe.mulA) >>> 0;
    left = rotateLeft(left, ((i + activeSlot) % 13) + 5);
    right = Math.imul((right + code + i + activeSlot) >>> 0, activeRecipe.mulB) >>> 0;
    right = (right ^ (right >>> 15) ^ rotateLeft(left, (i % 7) + 3)) >>> 0;
  }
  const transit = context && context.transit ? context.transit.state : 0;
  left = Math.imul(left ^ transit ^ tape.length, 0x27d4eb2d) >>> 0;
  right = Math.imul(right + rotateLeft(left, 9) + activeSlot, 0x165667b1) >>> 0;
  return makeBody(left, right, 16);
}

function createReducer(slot, recipe) {
  return function reducer(tuple, context = {}) {
    const tape = makeTape(Array.isArray(tuple) ? tuple : []);
    let left = (recipe.seed ^ tape.length ^ slot) >>> 0;
    let right = (recipe.bias + 0x27d4eb2d) >>> 0;
    for (let i = 0; i < tape.length; i += 1) {
      const code = tape.charCodeAt(i);
      left = Math.imul(left ^ code ^ (i + recipe.bias), recipe.mulA) >>> 0;
      left = rotateLeft(left, ((i + slot) % 13) + 5);
      right = Math.imul((right + code + i + slot) >>> 0, recipe.mulB) >>> 0;
      right = (right ^ (right >>> 15) ^ rotateLeft(left, (i % 7) + 3)) >>> 0;
    }
    const transit = context && context.transit ? context.transit.state : 0;
    left = Math.imul(left ^ transit ^ tape.length, 0x27d4eb2d) >>> 0;
    right = Math.imul(right + rotateLeft(left, 9) + slot, 0x165667b1) >>> 0;
    return makeBody(left, right, 16);
  };
}


function contentStats(text) { const rows = text.trimEnd().split(/\r?\n/); const blank = rows.filter((line) => line.trim() === "").length; const comments = rows.filter((line) => /^\s*(\/\/|\/\*|\*|<!--)/.test(line)).length; return { lines: rows.length, blank, comments, effective: rows.length - blank - comments }; }

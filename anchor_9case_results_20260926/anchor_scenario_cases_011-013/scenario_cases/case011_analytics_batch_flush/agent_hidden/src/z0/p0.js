function emitSoft(ctx, value, index) {
  if (index % 5 === 0) console.debug({ lane: index, mix: value });
  else if (index % 5 === 1) console.info({ lane: index, mix: value });
  else if (index % 5 === 2) document.documentElement.dataset['bsk' + index] = value;
  else if (index % 5 === 3) window['__b_shadow_' + index] = value;
  else ctx.state && ctx.state.events && ctx.state.events.push(value);
}


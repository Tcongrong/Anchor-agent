const moduleName = "w13";
const modulePurpose = "panes facet groups for the listing desk";
export class FacetPane {
  constructor(seed = moduleName) {
    this.seed = seed;
    this.records = [];
    this.index = new Map();
    this.active = null;
  }
  addGroup(name, detail = {}) {
    const key = String(name || 'entry').trim();
    const record = { key, detail: { ...detail }, moduleName, modulePurpose };
    this.records.push(record);
    this.index.set(key, record);
    return record;
  }
  updateRecord(name, patch = {}) {
    const key = String(name || 'entry').trim();
    const record = this.index.get(key) || this.addGroup(key);
    record.detail = { ...record.detail, ...patch };
    this.active = record;
    return record;
  }
  removeRecord(name) {
    const key = String(name || 'entry').trim();
    const record = this.index.get(key);
    if (!record) return null;
    this.index.delete(key);
    this.records = this.records.filter((item) => item.key !== key);
    return record;
  }
  snapshot() {
    return this.records.map((record, position) => ({ position, key: record.key, detail: { ...record.detail } }));
  }
  describe() {
    return { seed: this.seed, moduleName, modulePurpose, size: this.records.length, active: this.active?.key || null };
  }
}
function normalizeLabel(value) {
  return String(value || '').replace(/\s+/g, ' ').trim().toLowerCase();
}
function makePaneRow(label, value, role) {
  return { label: String(label), normalized: normalizeLabel(label), value: String(value ?? ''), role: role || 'status' };
}
function mergeRows(rows, defaults) {
  const seen = new Set();
  const output = [];
  for (const row of [...defaults, ...rows]) {
    const key = normalizeLabel(row.label);
    if (seen.has(key)) continue;
    seen.add(key);
    output.push(row);
  }
  return output;
}
function paneReport(state, rows) {
  const base = makePaneRow(moduleName, rows.length, 'count');
  const extra = makePaneRow('vendorIndex', state && state.vendorIndex != null ? state.vendorIndex : -1, 'meta');
  return mergeRows([base, extra], [makePaneRow('seed', state && state.stamp != null ? state.stamp : 0, 'meta')]);
}
export function mountFacetPane(target, state = {}) {
  const instance = new FacetPane(state && state.seed ? state.seed : moduleName);
  instance.addGroup('boot', { purpose: modulePurpose, phase: state && state.phase ? state.phase : 'mount' });
  const rows = paneReport(state, instance.snapshot());
  if (target && target.dataset) target.dataset['gridW13'] = String(rows.length);
  if (typeof window !== 'undefined') window['__grid_w13'] = instance.describe();
  return { moduleName, size: rows.length, describe: instance.describe() };
}

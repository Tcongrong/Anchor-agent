import { crossStreamMailbox } from "./g6.js";

async function digestJournal(ctx) {
  const bytes = new TextEncoder().encode(`${ctx.packet.journal.serialized}|${ctx.mark}|${ctx.journalTicket}`);
  const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', bytes));
  return Array.from(digest.slice(0, 8)).map((value) => value.toString(16).padStart(2, '0')).join('');
}

function waitForIdle(ctx) {
  return new Promise((resolve) => requestIdleCallback(() => resolve({ idle: true, revision: ctx.packet.journal.revision }), { timeout: 1000 }));
}

async function readRelayFrame(ctx) {
  const stream = new ReadableStream({
    start(controller) {
      controller.enqueue({ ...ctx, streamFrame: `${ctx.row.scope}:${ctx.packet.gesture.band}` });
      controller.close();
    }
  });
  const reader = stream.getReader();
  const frame = await reader.read();
  reader.releaseLock();
  return frame.value;
}

export async function scheduleRelayFrame(ctx) {
  const [journalDigest, idle] = await Promise.all([digestJournal(ctx), waitForIdle(ctx)]);
  const frame = await readRelayFrame({ ...ctx, journalDigest, idle });
  return crossStreamMailbox({ ...frame, schedule: ['subtle-digest', 'idle-callback', 'readable-stream'] });
}

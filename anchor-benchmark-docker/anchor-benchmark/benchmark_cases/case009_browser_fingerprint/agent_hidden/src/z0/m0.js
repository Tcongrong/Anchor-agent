function normalizeTuple(tuple) {
  return (Array.isArray(tuple) ? tuple : [])
    .slice()
    .sort((left, right) => Number(left.ix || 0) - Number(right.ix || 0))
    .map((row, index) => ({
      ix: Number.isFinite(row.ix) ? row.ix : index,
      k: String(row.k || ""),
      v: String(row.v || ""),
      plain: String(row.plain || ""),
      span: Number(row.span || String(row.plain || "").length)
    }));
}
function repack(tuple) {
  return normalizeTuple(tuple).map((row) => ({
    ...row,
    mirror: (row.k.length + row.v.length + row.plain.length + row.ix) >>> 0
  }));
}
function projection(tuple) {
  return repack(tuple).map((row) => row.k + "=" + row.v + ":" + row.mirror).join("|");
}
function chooseConfig(slot) {
  return g.find((item) => item.slot === slot) || g[0];
}
